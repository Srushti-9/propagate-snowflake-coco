-- PROPAGATE :: Phase 4 :: 14_phase4_agent.sql
-- Cortex Investigation Agent: natural-language investigation layer over
-- the propagation engine and evidence layer.
--
-- Creates:
--   ANALYTICS.V_CHAIN_INVESTIGATION (view)   - pre-joined chain edges + evidence
--   ANALYTICS.PROPAGATE_ANALYTICS (SV)       - semantic view for Cortex Analyst
--   ANALYTICS.PROPAGATE_AGENT (agent)        - Cortex Agent for investigation
--
-- Does NOT modify: SCORED_EDGES, CHAIN_EDGES, CHAINS, LAG_WINDOWS,
--   PROPAGATION_EVIDENCE, PROPAGATION_EVIDENCE_SUMMARY, or any Phase 2/3 object.

--------------------------------------------------------------------------------
-- Step 1: Investigation view (joins chain edges with evidence summaries)
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW PROPAGATE.ANALYTICS.V_CHAIN_INVESTIGATION AS
SELECT
    ce.CHAIN_ID,
    ce.STEP_NO,
    ce.EDGE_ID,
    ce.RELATION,
    ce.EVIDENCE_SCORE  AS structural_score,
    ce.EVIDENCE_CLASS  AS structural_class,
    fe.EVENT_TYPE      AS source_event_type,
    fe.BUSINESS_FUNCTION AS source_function,
    fe.ENTITY_ID       AS source_entity,
    fe.EVENT_TIME      AS source_time,
    te.EVENT_TYPE      AS target_event_type,
    te.BUSINESS_FUNCTION AS target_function,
    te.ENTITY_ID       AS target_entity,
    te.EVENT_TIME      AS target_time,
    DATEDIFF('day', fe.EVENT_TIME, te.EVENT_TIME) AS lag_days,
    COALESCE(fe.LINK_REGION, te.LINK_REGION) AS region,
    COALESCE(pes.EVIDENCE_STATUS, 'NO_DOCUMENT_EVIDENCE') AS document_evidence_status,
    COALESCE(pes.SUPPORTING_COUNT, 0)     AS supporting_doc_count,
    COALESCE(pes.CONTRADICTING_COUNT, 0)  AS contradicting_doc_count,
    pes.DOCUMENT_EVIDENCE_SCORE           AS document_score,
    pes.STRONGEST_SUPPORT                 AS support_summary,
    pes.STRONGEST_SUPPORT_SNIPPET         AS support_snippet,
    pes.STRONGEST_SUPPORT_DOC             AS support_doc_id,
    pes.STRONGEST_CONTRADICTION           AS contradiction_summary,
    pes.STRONGEST_CONTRADICTION_SNIPPET   AS contradiction_snippet,
    pes.STRONGEST_CONTRADICTION_DOC       AS contradiction_doc_id,
    ch.ROOT_TYPE,
    ch.IMPACT_TYPE,
    ch.IMPACT_REGION,
    ch.CHAIN_STATUS,
    ch.COHERENCE_SCORE,
    ch.INTERVENTION_LEAD_DAYS,
    ch.EARLIEST_INTERVENTION_EVENT,
    ch.INTERVENTION_FUNCTION
FROM PROPAGATE.ANALYTICS.CHAIN_EDGES ce
JOIN PROPAGATE.ANALYTICS.EVENT_LOG fe ON fe.EVENT_ID = ce.FROM_EVENT
JOIN PROPAGATE.ANALYTICS.EVENT_LOG te ON te.EVENT_ID = ce.TO_EVENT
JOIN PROPAGATE.ANALYTICS.CHAINS ch ON ch.CHAIN_ID = ce.CHAIN_ID
LEFT JOIN PROPAGATE.ANALYTICS.PROPAGATION_EVIDENCE_SUMMARY pes
    ON pes.EDGE_ID = ce.EDGE_ID AND pes.CHAIN_ID = ce.CHAIN_ID;

--------------------------------------------------------------------------------
